    /*// 1.21.1: copy — the mutation does NOT persist. The value stayed 100.
        check(StackNbt.getLong(stack, "energy") == 100L,
                "1.21.1: getItemTag returns copy, direct mutation must NOT persist (use editItemTag)");
        *///?}
