    // ════════════════════════════════════════════════════════════════════════
    //  Parity 9: save/load of ItemStack with NBT — round-trip preserves custom NBT.
    //  CRITICAL: on 1.21.1 the NBT is stored in the CUSTOM_DATA DataComponent.
    // ════════════════════════════════════════════════════════════════════════

    @GameTest(template = "empty3x3x3", batch = "parity", timeoutTicks = 100)
    public static void parity_saveLoad_preservesCustomNbt(GameTestHelper helper) {
        var provider = helper.getLevel().registryAccess();
        ItemStack original = new ItemStack(Items.DIAMOND);
        StackNbt.putLong(original, "energy", 4242L);
        StackNbt.putString(original, "serial", "RX-001");
        StackNbt.putInt(original, "tier", 5);

        CompoundTag saved = StackNbt.saveNew(original, provider);
        ItemStack loaded = StackNbt.parse(saved, provider);

        check(loaded.getItem() == Items.DIAMOND, "item type must survive save/load");
        check(StackNbt.getLong(loaded, "energy") == 4242L, "custom long must survive save/load");
        check("RX-001".equals(StackNbt.getString(loaded, "serial")), "custom string must survive save/load");
        check(StackNbt.getInt(loaded, "tier") == 5, "custom int must survive save/load");
        helper.succeed();
    }

